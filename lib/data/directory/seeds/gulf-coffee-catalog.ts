export function listGulfCoffeeCatalogByRoaster(roasterSlug: string): GulfCoffeeCatalogSeed[] {
  return GULF_COFFEE_CATALOG_SEEDS.filter((coffee) => coffee.roasterSlug === roasterSlug);
}

export function getGulfCoffeeCatalogEntry(roasterSlug: string, coffeeSlug: string): GulfCoffeeCatalogSeed | null {
  return (
    GULF_COFFEE_CATALOG_SEEDS.find(
      (coffee) => coffee.roasterSlug === roasterSlug && coffee.slug === coffeeSlug,
    ) ?? null
  );
}

export function coffeeCatalogKey(coffee: Pick<GulfCoffeeCatalogSeed, "roasterSlug" | "slug">): string {
  return `${coffee.roasterSlug}/${coffee.slug}`;
}
